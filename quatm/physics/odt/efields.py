class DCTrap():
    """DC 阱：由离子、杂散场（均值/标准差）与曲率构造 efields 计算器。

    平均杂散场与标准差按高斯假设互相换算（avg = sig·sqrt(2/π)）。

    Args:
        ion (Atom): 离子对象。
        sig_stray: 杂散场标准差（未给 avg_stray 时使用）。
        avg_stray: 杂散场均值（给定则覆盖 sig_stray）。
        curv: 曲率分量。

    Attributes:
        avg_trap (efields): 以平均杂散场构造的场计算器。
    """
    def __init__(self, ion, sig_stray=np.array([0,0,0]),
                 avg_stray=None, curv=np.array([0,0,0])):
        """构造 DC 阱。

        Args:
            ion (Atom): 离子对象。
            sig_stray: 杂散场标准差。
            avg_stray: 杂散场均值（None 则由 sig 换算）。
            curv: 曲率分量。
        """
        self.ion  = ion
        self.curv = curv

        if avg_stray is not None:
            self._avg_stray = avg_stray
            self._sig_stray = avg_stray/np.sqrt(2/np.pi)

        else:
            self._sig_stray = sig_stray
            self._avg_stray = sig_stray*np.sqrt(2/np.pi)

        self.avg_trap = efields(self.ion, self._avg_stray, self.curv)

    @property
    def sig_stray(self):
        """返回杂散电场标准差分量（V/m），描述场涨落的统计宽度，供随机建模用。"""
        return self._sig_stray

    @property
    def avg_stray(self):
        """返回杂散电场平均分量（V/m），描述场的系统偏移，供平均位移计算用。"""
        return self._avg_stray

    @sig_stray.setter
    def sig_stray(self, sig_stray):
        """设置杂散场标准差并同步换算均值。

        Args:
            sig_stray: 新标准差。
        """
        self._sig_stray = sig_stray
        self._avg_stray = sig_stray*np.sqrt(2/np.pi)

    @avg_stray.setter
    def avg_stray(self, avg_stray):
        """设置杂散场均值并同步换算标准差。

        Args:
            avg_stray: 新均值。
        """
        self._avg_stray = avg_stray
        self._sig_stray = avg_stray/np.sqrt(2/np.pi)



