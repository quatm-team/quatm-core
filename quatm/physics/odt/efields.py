"""Electric-field models for optical-dipole traps."""

from scipy import constants as const
import numpy as np

class efields(object):
    """DC 阱电场/势计算：线性势 + 四极（曲率）势 + 离子间库仑作用。

    Args:
        ion (Atom): 离子对象。
        stray: 杂散电场三分量（V/m）。
        curv: 曲率分量（决定囚禁频率）。
        f_RF: RF 贡献（可选）。
    """
    def __init__(self,ion,stray,curv,f_RF=np.zeros(3)):
        """构造电场计算器。

        Args:
            ion (Atom): 离子对象。
            stray: 杂散电场分量。
            curv: 曲率分量。
            f_RF: RF 贡献分量（默认 0）。
        """
        #self.name = name
        self.stray = np.array(stray)
        self.curv = np.array(curv)
        self.f_RF = f_RF
        self.ion = ion

    def curvx(self):
        """返回 x 方向的曲率分量（供 AnalTrapDepth 等默认使用）。"""
        return self.curv[0]

    def curvy(self):
        """返回 y 方向的曲率分量，用于计算该方向上的囚禁频率与势深。"""
        return self.curv[1]

    def curvz(self):
        """返回 z 方向曲率分量，用于计算轴向囚禁频率与势深（供模型使用）。"""
        return self.curv[2]

    def strayx(self):
        """返回 x 方向杂散电场分量（单位 V/m），供位移计算使用。"""
        return self.stray[0]

    def strayy(self):
        """返回 y 方向杂散电场分量（单位 V/m），供位移计算使用。"""
        return self.stray[1]

    def strayz(self):
        """返回 z 方向杂散电场分量（单位 V/m），供位移计算使用。"""
        return self.stray[2]



    def potential(self, point, ion_pos = None):
        """计算指定空间点处的电场势（含杂散场与阱内离子库仑项）。

        Args:
            point (list|np.ndarray): 三维坐标。
            ion_pos (list[np.ndarray]|None): 阱内离子位置列表；给出时计入库仑项。

        Returns:
            float: 该点的势能值。
        """
    
        coords = np.array(point)
        linPot = -const.e*np.dot(self.stray,coords)
        omega_squared =(2*const.pi)**2*(self.curv*abs(self.curv)
                                        +self.f_RF*abs(self.f_RF))
        quadPot = self.ion.mass/2*np.einsum('i, i...', omega_squared, coords**2)
        interact_Pot = 0
        
        if ion_pos is not None:
            recip_distances = 1/np.linalg.norm(point-ion_pos, axis = 1)
            prefac = const.e**2/(4*np.pi*const.epsilon_0)
            interact_Pot = prefac*np.sum(recip_distances)
        
        return linPot+quadPot+interact_Pot
    
    
    def iondistscale(self):
        """返回特征长度标度因子（D. James 冷阱离子量子动力学公式）。"""
        return (self.ion.charge**2./(4.*const.pi*const.epsilon_0*self.ion.mass*(2*const.pi*self.curvz())**2))**(1/3.)

    
